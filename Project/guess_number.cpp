#include <stdio.h>
#include <stdlib.h>
#include<time.h>

int main()
{
    int random, guess, attemp=0;
    srand(time(NULL));

    printf("welcome to the number guessing game!!!!!\n");
    random = (rand() % 100) + 1;  //generating between 1 to 100


    do{
        
    printf("\nguess the number between 1 to 100:-");
    scanf("%d", &guess);

        attemp++;

        if(guess<random)
        {
            printf("\nguess the larger number.");
        }
        else if(guess>random)
        {
            printf("\nguess the smaller number.");
        }
        else
        {
            printf("\ncongratulations!!!!, you have successfully guessed the number in %d attempts\n", attemp);
        }
    }while(random != guess);

    printf("Number generated by computer is %d", random);

    printf("\nBYE !!!  BYE  !!! thank you for playing with us. ");
}